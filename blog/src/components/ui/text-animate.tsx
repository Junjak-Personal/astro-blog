function TextAnimateBase({
  children,
  text,
  delay = 0,
  duration = 0.3,
  variants,
  className,
  segmentClassName,
  as: Component = 'p',
  startOnView = true,
  once = false,
  by = 'word',
  animation = 'fadeIn',
  accessible = true,
  ...props
}: TextAnimateProps) {
  const MotionComponent = useMemo(() => motion.create(Component), [Component]);
  const shouldReduceMotion = useReducedMotion();
  const content = text || (typeof children === 'string' ? children : '');

  let segments: string[] = [];
  switch (by) {
    case 'word':
      segments = content.split(/(\s+)/);
      break;
    case 'character':
      segments = content.split('');
      break;
    case 'line':
      segments = content.split('\n');
      break;
    case 'text':
    default:
      segments = [content];
      break;
  }

  const segmentCount = Math.max(segments.length, 1);

  const finalVariants = variants
    ? {
        container: {
          hidden: { opacity: 0 },
          show: {
            opacity: 1,
            transition: {
              opacity: { duration: 0.01, delay },
              delayChildren: delay,
              staggerChildren: duration / segmentCount,
            },
          },
          exit: {
            opacity: 0,
            transition: {
              staggerChildren: duration / segmentCount,
              staggerDirection: -1,
            },
          },
        },
        item: variants,
      }
    : animation
      ? {
          container: {
            ...defaultItemAnimationVariants[animation].container,
            show: {
              ...defaultItemAnimationVariants[animation].container.show,
              transition: {
                delayChildren: delay,
                staggerChildren: duration / segmentCount,
              },
            },
            exit: {
              ...defaultItemAnimationVariants[animation].container.exit,
              transition: {
                staggerChildren: duration / segmentCount,
                staggerDirection: -1,
              },
            },
          },
          item: defaultItemAnimationVariants[animation].item,
        }
      : { container: defaultContainerVariants, item: defaultItemVariants };

  return (
    <AnimatePresence mode="popLayout">
      <MotionComponent
        variants={shouldReduceMotion ? undefined : finalVariants.container as Variants}
        initial={shouldReduceMotion ? false : 'hidden'}
        whileInView={!shouldReduceMotion && startOnView ? 'show' : undefined}
        animate={shouldReduceMotion
          ? { opacity: 1, x: 0, y: 0, scale: 1, filter: 'none', transition: { duration: 0 } }
          : startOnView ? undefined : 'show'}
        exit={shouldReduceMotion ? undefined : 'exit'}
        className={cn('whitespace-pre-wrap', className)}
        viewport={{ once }}
        aria-label={accessible ? content : undefined}
        {...props}
      >
        {shouldReduceMotion
          ? content
          : (
              <>
                {accessible && <span className="sr-only">{content}</span>}
                {segments.map((segment, i) => (
                  <motion.span
                    key={`${by}-${segment}-${i}`}
                    variants={finalVariants.item}
                    custom={i * staggerTimings[by]}
                    className={cn(
                      by === 'line' ? 'block' : 'inline-block whitespace-pre',
                      segmentClassName,
                    )}
                    aria-hidden={accessible ? true : undefined}
                  >
                    {segment}
                  </motion.span>
                ))}
              </>
            )}
      </MotionComponent>
    </AnimatePresence>
  );
}

export const TextAnimate = memo(TextAnimateBase);
